"""Builds the layered splash screen of the editor from assets/brand/splash/src (one PNG per layer + layers.json from the design).
Output: assets/brand/splash/<layer>.png (scaled to the splash window) and crates/nord-editor/src/splash_layers.rs (positions).
To change a logo: replace assets/brand/splash/src/logo-*.png (same file name, any size: it is centred in the original box), run this, rebuild.
"""
import json, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "assets/brand/splash/src")
OUT = os.path.join(ROOT, "assets/brand/splash")
BOX = (40, 165, 563, 625)          # the splash panel inside the 1024x765 design
W, H = 600, 526                    # splash window size (points)
sx, sy = W / (BOX[2] - BOX[0]), H / (BOX[3] - BOX[1])
LAYERS = ["circuits-left", "circuits-right", "splash-emblem", "title", "tagline", "loading-text",
          "logo-phaser", "logo-babylon", "logo-havok", "logo-rust", "logo-eframe-egui"]  # draw order
meta = {l["id"]: l for l in json.load(open(os.path.join(SRC, "layers.json")))}

Image.open(os.path.join(SRC, "background.png")).convert("RGB").crop(BOX).resize((W, H), Image.LANCZOS).save(os.path.join(OUT, "background.png"))
rows = []
for name in LAYERS:
    m = meta[name]
    im = Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")
    # replacement art of another size is fitted into the original box (keeps the aspect ratio)
    r = min(m["w"] / im.width, m["h"] / im.height)
    if abs(r - 1) > 0.01:
        im = im.resize((max(1, round(im.width * r)), max(1, round(im.height * r))), Image.LANCZOS)
    box = Image.new("RGBA", (m["w"], m["h"]), (0, 0, 0, 0))
    box.alpha_composite(im, ((m["w"] - im.width) // 2, (m["h"] - im.height) // 2))
    w, h = round(m["w"] * sx), round(m["h"] * sy)
    box.resize((w, h), Image.LANCZOS).save(os.path.join(OUT, name + ".png"))
    rows.append((name, (m["x"] - BOX[0]) * sx, (m["y"] - BOX[1]) * sy, w, h))

with open(os.path.join(ROOT, "crates/nord-editor/src/splash_layers.rs"), "w") as f:
    f.write("//! GENERATED by tools/make_splash.py - do not edit. (name, x, y, w, h) in splash points, draw order.\n")
    f.write("use egui::{include_image, ImageSource};\n\n")
    f.write("pub const BACKGROUND: ImageSource<'static> = include_image!(\"../../../assets/brand/splash/background.png\");\n\n")
    f.write("pub struct Layer {\n    pub name: &'static str,\n    pub x: f32,\n    pub y: f32,\n    pub w: f32,\n    pub h: f32,\n    pub image: ImageSource<'static>,\n}\n\n")
    f.write("pub fn layers() -> Vec<Layer> {\n    vec![\n")
    for n, x, y, w, h in rows:
        f.write(f"        Layer {{ name: \"{n}\", x: {x:.1f}, y: {y:.1f}, w: {w}.0, h: {h}.0, image: include_image!(\"../../../assets/brand/splash/{n}.png\") }},\n")
    f.write("    ]\n}\n")
print("ok", len(rows), "layers")
