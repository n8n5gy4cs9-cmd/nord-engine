#!/usr/bin/env python3
"""Regenerate ALL placeholder assets (deterministic) and the inventory section of ASSETS.md.
Usage: python3 tools/gen_assets.py [brand|textures|sprites|audio|docs|md ...]   (no args = everything)
Needs: python3, numpy, Pillow, ffmpeg (mp3), headless Chromium (docs icons only). Crowelian 2026 + Sonnet."""
import sys, os, collections
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "gen"))
import common, brand, textures, sprites, audio, retro_audio

START, END = "<!-- INVENTORY:START (generated by tools/gen_assets.py — do not edit) -->", "<!-- INVENTORY:END -->"

def inventory():
    root = common.A; groups = collections.OrderedDict()
    for dp, dn, fn in sorted(os.walk(root)):
        dn.sort()
        rel = os.path.relpath(dp, root)
        files = [f for f in sorted(fn) if not f.endswith(".meta.json")]
        if files and rel != ".": groups[rel] = files
    lines = [START, ""]
    total = sum(len(v) for v in groups.values())
    lines.append(f"**{total} asset files** in {len(groups)} folders. Folder → files:\n")
    for rel, files in groups.items():
        if rel.startswith("icons/lucide"):
            lines.append(f"- `assets/{rel}/` — {len(files)} Lucide SVG icons (ISC licence; see `tools/lucide-icons.txt`)"); continue
        names = ", ".join(f"`{f}`" for f in files) if len(files) <= 40 else ", ".join(f"`{f}`" for f in files[:40]) + f", … (+{len(files) - 40})"
        lines.append(f"- `assets/{rel}/` ({len(files)}) — {names}")
    lines += ["", END]
    return "\n".join(lines)

def write_md():
    p = os.path.join(common.ROOT, "ASSETS.md"); s = open(p).read()
    a, b = s.index(START), s.index(END) + len(END)
    open(p, "w").write(s[:a] + inventory() + s[b:])

def docs_step():
    import docs_art
    docs_art.run()

if __name__ == "__main__":
    steps = {"brand": brand.run, "textures": textures.run, "sprites": sprites.run, "audio": audio.run, "retro-audio": retro_audio.run, "docs": docs_step, "md": write_md}
    for k in (sys.argv[1:] or list(steps)): steps[k]()
