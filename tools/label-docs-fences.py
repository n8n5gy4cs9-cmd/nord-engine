#!/usr/bin/env python3
"""One-off helper for docs/DOC_STYLE.md rule 1: adds a '**File: `path`**' / '**Terminal**' / '**Example**' label above code fences that have none.
The file name comes from (in order): an inline-code path or <span class="f"> or heading just above, `export default class Name` in the code,
the file named by the previous label on the same page. Anything it cannot place gets '**Example** (a fragment, not a whole file):'.
Review the diff! usage: python3 tools/label-docs-fences.py [--dry] [pages…]"""
import re, sys, pathlib
DIR = pathlib.Path(__file__).resolve().parent.parent / 'docs/manual-src'
dry = '--dry' in sys.argv
SKIP = {'tut-t33-code-coin-rush.md', 'tut-t34-code-crystal-relay.md'}   # generated by tools/build-code-workshops.mjs
pages = [pathlib.Path(a) for a in sys.argv[1:] if not a.startswith('--')] or [p for p in sorted(DIR.glob('*.md')) if p.name not in SKIP]
EXT = r'(?:js|json|md|glsl|py|html|mjs|css|rs|toml)'
LABEL = re.compile(r'^\s*(\*\*(File|In the file|Terminal|Example|Console output|Output|Result)\b|In a terminal)|`[\w./@-]+\.' + EXT + r'`|^#+ .*[\w/-]+\.' + EXT + r'\b|<span class="f">', re.I)
PATH = re.compile(r'`((?:[\w@-]+/)*[\w@.-]+\.' + EXT + r')`')
total = 0
for page in pages:
    text = page.read_text()
    head, sep, body = text.partition('\n---\n')
    if re.search(r'^style:\s*(reference|generated)', head, re.M): continue
    lines = text.split('\n'); out = []; ctx = None; in_fence = False; changed = 0
    for i, l in enumerate(lines):
        m = re.match(r'^```(\w*)', l)
        if m and not in_fence:
            in_fence = True; lang = m.group(1)
            if lang in ('js', 'javascript', 'json', 'bash', 'sh', 'glsl'):
                j = len(out) - 1
                while j >= 0 and out[j].strip() == '': j -= 1
                above = ' '.join(out[max(0, j - 1):j + 1]) if j >= 0 else ''
                code = []
                for k in range(i + 1, len(lines)):
                    if lines[k].startswith('```'): break
                    code.append(lines[k])
                code = '\n'.join(code)
                pm = PATH.findall(above)
                if pm: ctx = pm[-1]
                if j >= 0 and LABEL.search(out[j]) or LABEL.search(above):
                    pass
                else:
                    label = None
                    if lang in ('bash', 'sh'):
                        label = '**Terminal** (in the project folder):'
                    elif lang == 'json':
                        if re.search(r'"(display|physics|input|quality|startScene)"', code): label = '**In the file** `nord.project.json`:'; ctx = 'nord.project.json'
                        elif '"entities"' in code: label = '**In the file** `scenes/main.scene.json`:'
                        elif '"root"' in code and '"format"' in code: label = '**In the file** the prefab (`prefabs/<name>.prefab.json`):'
                        elif '"effects"' in code: label = '**In the file** `scenes/main.scene.json` (the scene\'s `settings`):'
                        else: label = '**In the file** (the JSON file named in the text above; compare it with what the editor wrote):'
                    else:
                        cm = re.search(r'export default class (\w+)', code)
                        if cm: label = f'**File: `scripts/{cm.group(1)}.js`** (new file, the whole file):'; ctx = f'scripts/{cm.group(1)}.js'
                        elif ctx: label = f'**File: `{ctx}`** (a fragment of this file, not a whole file):'
                        else: label = '**Example** (a fragment, not a whole file):'
                    if out and out[-1].strip(): out.append('')
                    out.append(label); changed += 1
        elif m and in_fence:
            in_fence = False
        out.append(l)
    if changed:
        total += changed
        print(f'{page.name}: {changed}')
        if not dry: page.write_text('\n'.join(out))
print('labels added:', total)
