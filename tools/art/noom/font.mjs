export function font(px) {
  const chars = Array.from({ length: 64 }, (_, i) => String.fromCharCode(i + 32));
  const cells = chars.map((ch) => px.grid(GLYPHS[ch].split('/'), { '0': null, '1': '#ffffff' }, `font:${ch}`));
  return px.sheet(cells.map((cell) => px.compose(6, 8, [[cell, 0, 0]])), 16);
}
