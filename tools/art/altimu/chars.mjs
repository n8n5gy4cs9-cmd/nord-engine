/** Six 16x16 frames for one person. */
export function person(px, key) {
  const def = PEOPLE[key], pal = { ...BASE, ...def.pal, '.': null }, out = [];
  for (const view of ['front', 'back', 'side']) {
    const head = HEAD[view][def.head] ?? HEAD[view].short;
    for (const step of [0, 1]) {
      const legs = def.robe ? ROBE[view][step] : LEGS[view][step];
      out.push(px.grid([...head, ...BODY[view], ...legs], pal, `person:${key}:${view}${step}`));
    }
  }
  return out;
}

